// Generates the Authzed.Net bridge: one [assembly: TypeForwardedTo] per exported top-level
// type in SpiceDB.Proto's generated namespaces. Nested types (Types.*) are forwarded with
// their declaring type. Usage: dotnet run --project bridge/generator -- <output file>
using System.Text;

var output = args.Length == 1 ? args[0] : throw new ArgumentException("usage: AuthzedNetBridgeGen <output file>");
var text = Render();
File.WriteAllText(output, text);
Console.WriteLine($"wrote {output}");

static string Render()
{
    var types = BridgeTypes.Forwarded();
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>");
    sb.AppendLine("// Generated by proto-clients/spicedb-csharp-proto/bridge/generator. DO NOT EDIT.");
    sb.AppendLine("// Forwards every generated authzed.api type to SpiceDB.Proto, the canonical binding.");
    sb.AppendLine("// </auto-generated>");
    sb.AppendLine("using System.Runtime.CompilerServices;");
    sb.AppendLine();
    foreach (var type in types)
        sb.AppendLine($"[assembly: TypeForwardedTo(typeof(global::{type.FullName}))]");
    return sb.ToString();
}

internal static class BridgeTypes
{
    /// <summary>The generated namespaces the legacy Authzed.Net assembly shares with SpiceDB.Proto.</summary>
    public static readonly string[] Namespaces = ["Authzed.Api.V1", "Authzed.Api.Materialize.V0"];

    public static IReadOnlyList<Type> Forwarded() =>
        typeof(Authzed.Api.V1.Relationship).Assembly.GetExportedTypes()
            .Where(t => !t.IsNested && Namespaces.Contains(t.Namespace))
            .OrderBy(t => t.FullName, StringComparer.Ordinal)
            .ToArray();
}
