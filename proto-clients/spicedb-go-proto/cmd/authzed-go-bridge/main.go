// Command authzed-go-bridge turns an authzed-go checkout's generated protocol
// packages into aliases of this module's canonical packages.
//
// Two independently generated copies of authzed.api.* cannot be linked into
// one Go binary: protoregistry panics on the second registration of the same
// proto file. This module is the canonical copy, so authzed-go stops
// generating its own and re-exports these packages instead. Run it from an
// authzed-go checkout that requires this module:
//
//	go run github.com/authzed/spicedb-clients/proto-clients/spicedb-go-proto/cmd/authzed-go-bridge -root .
//
// For each bridged package it deletes the generated *.pb.go, *.pb.validate.go
// and *.pb.gw.go files and the hand-written validation file (all of which now
// live here) and writes zz_generated.bridge.go, which declares a type alias,
// constant, variable or forwarding function for every exported identifier.
// Other files, such as zz_generated.version.go, are left alone.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/importer"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const canonicalPrefix = "github.com/authzed/spicedb-clients/proto-clients/spicedb-go-proto/gen/"

// bridged lists the authzed-go packages to bridge, relative to proto/ in
// authzed-go and to gen/ here.
var bridged = []string{"authzed/api/v1", "authzed/api/materialize/v0"}

func main() {
	root := flag.String("root", ".", "authzed-go repository root")
	flag.Parse()

	for _, rel := range bridged {
		dir := filepath.Join(*root, "proto", filepath.FromSlash(rel))
		src, err := Generate(canonicalPrefix + rel)
		if err != nil {
			log.Fatalf("%s: %v", rel, err)
		}
		if err := removeGenerated(dir); err != nil {
			log.Fatalf("%s: %v", rel, err)
		}
		if err := os.WriteFile(filepath.Join(dir, "zz_generated.bridge.go"), src, 0o644); err != nil {
			log.Fatalf("%s: %v", rel, err)
		}
		fmt.Printf("bridged %s\n", dir)
	}
}

// IsBridgedFile reports whether name is a file the bridge replaces.
func IsBridgedFile(name string) bool {
	return strings.HasSuffix(name, ".pb.go") ||
		strings.HasSuffix(name, ".pb.validate.go") ||
		strings.HasSuffix(name, ".pb.gw.go") ||
		name == "00_handwritten_validation.go"
}

func removeGenerated(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if !e.IsDir() && IsBridgedFile(e.Name()) {
			if err := os.Remove(filepath.Join(dir, e.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}

// Generate returns the alias source for the canonical package at importPath.
func Generate(importPath string) ([]byte, error) {
	pkg, err := importer.ForCompiler(token.NewFileSet(), "source", nil).Import(importPath)
	if err != nil {
		return nil, err
	}
	scope := pkg.Scope()
	names := scope.Names()
	sort.Strings(names)

	// Inside the alias package every canonical identifier has an alias of
	// the same name, so signatures refer to them unqualified.
	imports := map[string]string{}
	qualifier := func(p *types.Package) string {
		if p.Path() == importPath {
			return ""
		}
		imports[p.Path()] = p.Name()
		return p.Name()
	}

	var types_, consts, vars, funcs bytes.Buffer
	for _, name := range names {
		obj := scope.Lookup(name)
		if !obj.Exported() {
			continue
		}
		switch o := obj.(type) {
		case *types.TypeName:
			if named, ok := o.Type().(*types.Named); ok && named.TypeParams().Len() > 0 {
				return nil, fmt.Errorf("generic type %s cannot be aliased", name)
			}
			fmt.Fprintf(&types_, "\t%s = canonical.%s\n", name, name)
		case *types.Const:
			fmt.Fprintf(&consts, "\t%s = canonical.%s\n", name, name)
		case *types.Var:
			fmt.Fprintf(&vars, "\t%s = canonical.%s\n", name, name)
		case *types.Func:
			sig := o.Type().(*types.Signature)
			if sig.TypeParams().Len() > 0 {
				return nil, fmt.Errorf("generic func %s cannot be forwarded", name)
			}
			writeForwarder(&funcs, name, sig, qualifier)
		}
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by authzed-go-bridge. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// Package %s re-exports %s, the canonical generated binding.\n", pkg.Name(), importPath)
	fmt.Fprintf(&out, "package %s\n\nimport (\n\tcanonical %q\n", pkg.Name(), importPath)
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&out, "\t%s %q\n", imports[p], p)
	}
	out.WriteString(")\n\n")
	for _, block := range []struct {
		kw  string
		buf *bytes.Buffer
	}{{"type", &types_}, {"const", &consts}, {"var", &vars}} {
		if block.buf.Len() > 0 {
			fmt.Fprintf(&out, "%s (\n%s)\n\n", block.kw, block.buf.String())
		}
	}
	out.Write(funcs.Bytes())
	return format.Source(out.Bytes())
}

func writeForwarder(w *bytes.Buffer, name string, sig *types.Signature, q types.Qualifier) {
	var params, args []string
	for i := 0; i < sig.Params().Len(); i++ {
		p := sig.Params().At(i)
		arg := fmt.Sprintf("p%d", i)
		typ := types.TypeString(p.Type(), q)
		if sig.Variadic() && i == sig.Params().Len()-1 {
			typ = "..." + types.TypeString(p.Type().(*types.Slice).Elem(), q)
			arg += "..."
		}
		params = append(params, fmt.Sprintf("p%d %s", i, typ))
		args = append(args, arg)
	}
	results := types.TypeString(sig.Results(), q)
	if sig.Results().Len() == 1 && sig.Results().At(0).Name() == "" {
		results = types.TypeString(sig.Results().At(0).Type(), q)
	}
	ret := "return "
	if sig.Results().Len() == 0 {
		ret = ""
	}
	fmt.Fprintf(w, "func %s(%s) %s {\n\t%scanonical.%s(%s)\n}\n\n", name, strings.Join(params, ", "), results, ret, name, strings.Join(args, ", "))
}
