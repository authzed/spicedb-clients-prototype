# frozen_string_literal: true

# Rewrites a checkout of the official `authzed` gem (authzed/authzed-rb, or an
# unpacked .gem) so that it uses spicedb-proto's generated bindings instead of
# shipping its own. Root DESIGN.md, "Be the single copy of the protocol
# bindings in any process": Ruby's Google::Protobuf::DescriptorPool admits one
# definition per proto file, so two independently generated copies of
# authzed/api/v1/core.proto in one process raise "duplicate file name" at load
# time. The legacy gem migrates by depending on this one.
#
# What it does, in order, failing before any change if a step cannot succeed:
#   1. finds every protoc-generated `*_pb.rb` under the checkout's lib/
#      (authzed/api/**, google/**, buf/**, validate/**, protoc-gen-openapiv2/**);
#   2. checks that each one's require path is served after the bridge, either
#      by spicedb-proto's lib/gen or by googleapis-common-protos-types (for
#      google/api and google/rpc), so `require 'authzed/api/v1/core_pb'` and
#      friends keep working for the legacy gem's own users;
#   3. deletes those files (and directories left empty);
#   4. makes lib/authzed.rb require 'spicedb_proto' first, which puts the
#      canonical bindings at the front of the load path;
#   5. adds a runtime dependency on spicedb-proto to every *.gemspec.
# Hand-written files (authzed/api/v1/client.rb, grpcutil/bearer_token.rb) are
# kept. Running it twice is a no-op. The checkout's own code generation (for
# example a buf.gen.yaml) must stop emitting the deleted files; the report
# lists any generation config it finds.
#
# Usage: bundle exec ruby bridge/authzed_bridge.rb [--dry-run] AUTHZED_CHECKOUT
require "fileutils"

module AuthzedBridge
  GENERATED = /Generated by the protocol buffer compiler/
  MARKER = "# spicedb-proto bridge"
  DEFAULT_REQUIREMENT = ">= 0.1"

  class Error < StandardError; end

  Report = Struct.new(:deleted, :entrypoint_rewritten, :gemspecs_rewritten, :generation_configs, keyword_init: true)

  module_function

  # @return [Report]
  def run(root, proto_gen: File.expand_path("../lib/gen", __dir__), googleapis_lib: googleapis_lib_dir,
          requirement: DEFAULT_REQUIREMENT, dry_run: false)
    lib = File.join(root, "lib")
    entry = File.join(lib, "authzed.rb")
    raise Error, "#{root} does not look like the authzed gem: #{entry} is missing" unless File.file?(entry)

    generated = generated_files(lib)
    unresolved = generated.reject { |path| served?(path.delete_prefix("#{lib}/"), proto_gen, googleapis_lib) }
    unless unresolved.empty?
      raise Error, "these authzed require paths would not resolve after the bridge (spicedb-proto has no such file): " +
                   unresolved.map { |path| path.delete_prefix("#{lib}/") }.join(", ")
    end

    report = Report.new(deleted: generated.map { |path| path.delete_prefix("#{lib}/") }, entrypoint_rewritten: false,
                        gemspecs_rewritten: [], generation_configs: Dir[File.join(root, "{buf.gen.yaml,buf.gen.*.yaml,Rakefile}")])
    return report if dry_run

    generated.each { |path| File.delete(path) }
    prune_empty_dirs(lib)
    report.entrypoint_rewritten = rewrite_entrypoint(entry)
    report.gemspecs_rewritten = Dir[File.join(root, "*.gemspec")].select { |gemspec| rewrite_gemspec(gemspec, requirement) }
    report
  end

  def generated_files(lib)
    Dir[File.join(lib, "**", "*_pb.rb")].select { |path| File.foreach(path).first(3).any? { |line| line.match?(GENERATED) } }.sort
  end

  def served?(relative, proto_gen, googleapis_lib)
    File.file?(File.join(proto_gen, relative)) || (googleapis_lib && File.file?(File.join(googleapis_lib, relative)))
  end

  def googleapis_lib_dir
    Gem::Specification.find_by_name("googleapis-common-protos-types").full_require_paths.first
  rescue Gem::MissingSpecError
    nil
  end

  def prune_empty_dirs(lib)
    Dir[File.join(lib, "**", "*/")].sort_by { |dir| -dir.length }.each do |dir|
      Dir.rmdir(dir) if Dir.empty?(dir)
    end
  end

  def rewrite_entrypoint(entry)
    source = File.read(entry)
    return false if source.include?(MARKER)

    line = "require 'spicedb_proto' #{MARKER}: the canonical authzed.api bindings\n"
    File.write(entry, source.sub(/\A((?:#.*\n)*)/) { "#{Regexp.last_match(1)}#{line}" })
    true
  end

  def rewrite_gemspec(gemspec, requirement)
    source = File.read(gemspec)
    return false if source.include?("spicedb-proto")

    variable = source[/Gem::Specification\.new\s+do\s+\|(\w+)\|/, 1]
    raise Error, "#{gemspec}: cannot find the Gem::Specification.new block" unless variable

    index = source.rindex(/^end\b/)
    raise Error, "#{gemspec}: cannot find the end of the specification block" unless index

    dependency = "  #{variable}.add_dependency 'spicedb-proto', '#{requirement}' #{MARKER}\n"
    File.write(gemspec, source.dup.insert(index, dependency))
    true
  end
end

if $PROGRAM_NAME == __FILE__
  dry_run = ARGV.delete("--dry-run")
  abort "usage: ruby #{$PROGRAM_NAME} [--dry-run] AUTHZED_CHECKOUT" unless ARGV.length == 1
  begin
    report = AuthzedBridge.run(ARGV.first, dry_run: !dry_run.nil?)
  rescue AuthzedBridge::Error => e
    abort "authzed-bridge: #{e.message}"
  end
  puts "#{dry_run ? 'would delete' : 'deleted'} #{report.deleted.length} generated file(s):"
  report.deleted.each { |path| puts "  lib/#{path}" }
  puts "rewrote lib/authzed.rb" if report.entrypoint_rewritten
  report.gemspecs_rewritten.each { |path| puts "added spicedb-proto to #{File.basename(path)}" }
  report.generation_configs.each { |path| puts "NOTE: #{File.basename(path)} may regenerate the deleted files; stop it emitting them" }
end
