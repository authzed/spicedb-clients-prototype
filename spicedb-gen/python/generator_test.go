// TestRuffFormatClean requires generated output to be `ruff format` clean,
// including a schema whose long names force line wrapping. The Magefile's
// PythonFormatCheck enforces the same in CI; this runs when ruff is installed.
func TestRuffFormatClean(t *testing.T) {
	ruff, err := exec.LookPath("ruff")
	if err != nil {
		t.Skip("ruff not installed")
	}
	long := parse(t, `
use expiration
caveat regional_network_policy(allowed_network_range string) { allowed_network_range == "" }
definition service_account_identity {}
definition organization_workspace_project {
	relation delegated_administrator: service_account_identity | service_account_identity with regional_network_policy | service_account_identity:* | service_account_identity with expiration
	permission administer_billing_settings = delegated_administrator
}
definition holder {
	relation grant: organization_workspace_project#administer_billing_settings with expiration
}`)
	single := parse(t, "definition user {}\ndefinition team {\n relation member: user\n}")
	renamed := map[string]string{"rename": "subject=SubjectDef"}
	for i, s := range []*schema.Schema{testSchema(t), long, single, parse(t, collidingSchema)} {
		var opts map[string]string
		if i == 3 {
			opts = renamed
		}
		for name, content := range generate(t, s, opts) {
			cmd := exec.Command(ruff, "format", "--isolated", "--diff", "--stdin-filename", name, "-")
			cmd.Stdin = strings.NewReader(content)
			var out bytes.Buffer
			cmd.Stdout, cmd.Stderr = &out, &out
			assert.NoError(t, cmd.Run(), "%s is not ruff-format clean:\n%s", name, out.String())

			cmd = exec.Command(ruff, "check", "--isolated", "--select", "E4,E7,E9,F", "--stdin-filename", name, "-")
			cmd.Stdin = strings.NewReader(content)
			out.Reset()
			cmd.Stdout, cmd.Stderr = &out, &out
			assert.NoError(t, cmd.Run(), "%s fails ruff check:\n%s", name, out.String())
		}
	}
}

func TestFormattingHelpers(t *testing.T) {
	assert.Equal(t, "    def f(self) -> X:", bracket(4, "def f", list("self"), " -> X:"))
	long := strings.Repeat("a", 40)
	assert.Equal(t, "    def f(\n        self, subject: "+long+"\n    ) -> "+long+":",
		bracket(4, "def f", list("self", "subject: "+long), " -> "+long+":"))
	exploded := bracket(0, "f", list(strings.Repeat("b", 50), strings.Repeat("c", 50)), "")
	assert.Equal(t, "f(\n    "+strings.Repeat("b", 50)+",\n    "+strings.Repeat("c", 50)+",\n)", exploded)
	assert.Equal(t, "X = ()", tuple("X", nil))
	assert.Equal(t, `X = ("a",)`, tuple("X", list("a")))
	assert.Equal(t, "X = (\n    \"a\",\n    \"b\",\n)", tuple("X", list("a", "b")))
	assert.Equal(t, "A: TypeAlias = B | C", formatAlias("A", list("B", "C")))
}

