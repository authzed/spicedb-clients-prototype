// TestCollisionsFailGeneration: generated identifiers are never silently
// renamed; a collision names both of its sources.
func TestCollisionsFailGeneration(t *testing.T) {
	for name, tc := range map[string]struct {
		zed  string
		want []string
	}{
		"key accessor vs relation writer": {
			zed:  "use expiration\ndefinition user {}\ndefinition doc {\n relation admin: user with expiration\n relation admin_key: user\n}",
			want: []string{"DocAdminKeySubject", "key subjects of relation doc#admin", "subjects of relation doc#admin_key"},
		},
		"relation vs built-in member": {
			zed:  "definition user {}\ndefinition doc {\n relation filter: user\n}",
			want: []string{"filter", "built-in member filter", "writer for relation filter"},
		},
		"definition vs name constants": {
			zed:  "definition doc {}\ndefinition doc_relations {}",
			want: []string{"DocRelations", "relation names of doc", "definition doc_relations"},
		},
		"definition vs schema-level names": {
			zed:  "definition definition_names {}",
			want: []string{"DefinitionNames", "generated support code", "definition definition_names"},
		},
		"userset subject vs definition": {
			zed:  "definition user {}\ndefinition team {\n relation member: user\n}\ndefinition team_member {}\ndefinition doc {\n relation viewer: team#member\n}",
			want: []string{"TeamMember", "definition team_member", "subject team#member"},
		},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := (&Generator{}).Generate(parse(t, tc.zed), nil)
			require.Error(t, err)
			for _, w := range tc.want {
				assert.Contains(t, err.Error(), w)
			}
		})
	}
}

