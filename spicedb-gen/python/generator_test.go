func generate(t *testing.T, s *schema.Schema, opts map[string]string) map[string]string {
	t.Helper()
	files, err := (&Generator{}).Generate(s, opts)
	require.NoError(t, err)
	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = string(f.Content)
	}
	return out
}

func parse(t *testing.T, zed string) *schema.Schema {
	t.Helper()
	s, err := schema.ParseString(zed)
	require.NoError(t, err)
	return s
}

